.canonical_h_rows <- function(H) {
  unname(apply(H, 1L, function(row) paste(sort(row), collapse = ":")))
}

test_that("LLQR H row sets match the fixed source baseline", {
  set.seed(101)
  x <- sort(stats::runif(100))
  y <- 1 + 2 * x^2 + stats::rnorm(100)
  z <- seq(0.1, 0.9, length.out = 25)
  expected <- list(
    gaussian = c(
      "2:29", "2:29", "2:29", "2:29", "14:42", "14:42", "14:42",
      "19:37", "19:37", "19:62", "19:62", "19:62", "29:62", "27:63",
      "45:63", "45:74", "39:74", "39:74", "56:74", "56:98", "59:90",
      "59:92", "61:92", "69:96", "69:96"
    ),
    epanechnikov = c(
      "2:19", "2:19", "2:19", "2:19", "2:29", "29:51", "2:57", "2:62",
      "2:62", "29:63", "14:56", "14:56", "18:56", "18:56", "37:56",
      "37:63", "30:78", "30:98", "42:90", "63:90", "63:100", "56:92",
      "56:92", "78:92", "78:92"
    )
  )

  for (kernel in names(expected)) {
    fit <- llqr_seq_ppro(x, y, z = z, kernel = kernel)
    backend <- fastllqr:::.llqr_backend(
      x, y, 0.5, z, fit$h, kernel, 0.1
    )
    expect_identical(.canonical_h_rows(backend$H_seq), expected[[kernel]])
  }
})

